// check-api-vocabulary — fail when the FROZEN PUBLIC SURFACE still spells a name a decision retired.
//
// The gap this closes sits BETWEEN two gates that each work correctly:
//   · check-docs deliberately excludes `src/` (XML docs sit beside the code and the compiler gates their
//     crefs), so it never reads a parameter name;
//   · the API-surface baseline RECORDS parameter names without judging them. It reports THAT a name
//     changed, never THAT a name should have — so a stale name round-trips cleanly through the one gate
//     whose entire job is noticing API changes.
// Measured cost (TASKS.md Part 61, docs/DECISIONS.md D47): `GraphMemoryEngine(ageClocks:)`,
// `GraphMemoryEngine(appraisers:)` and `ModulatedRetrievability(modulators:)` kept the words "clock",
// "appraiser" and "modulator" all the way to the eve of the 3.0 freeze — the exact three words that
// decision retired. A human review caught all three; no gate did. **Named arguments are source-compatible
// public surface**, so after a freeze each one costs a major version.
//
// The registry is `retiredApiNames` in devtools/project.config.mjs — deliberately NOT `retiredTerms`,
// which is written for PROSE (claim shapes, qualified namespace paths) and is meaningless against a
// baseline, which is identifiers and signatures only.
//
// MATCHING IS WHOLE-IDENTIFIER, NEVER SUBSTRING, and that is the load-bearing property. The registry
// retires `modulators` and `IRetentionModulator` while `Lyntai.Memory.Modulation` (a namespace) and
// `ModulatedRetrievability` (a type) are LIVE — same root, opposite verdicts, both sides genuinely in
// today's baseline. It retires `MemoryRetentionPolicy` (the 3.0 collision fix) while the seam
// `IMemoryRetentionPolicy` is LIVE and contains it character-for-character, so here a substring rule would
// fire on the very name the rename exists to protect. And `InactivityClock` is a live type sharing a word
// with four retired `*Clock` policies. A substring rule fires on every one of them, and a gate that cries wolf on a
// deliberate decision gets an exclusion added and then rots — the failure mode `retiredTerms`'s own
// comments warn about for bare-name patterns.
// So each baseline line is TOKENIZED into identifiers and compared token-for-token: a `names` rule is set
// membership, a `pattern` rule is a regex anchored to the WHOLE token.
//
// The limit, stated plainly rather than oversold: this catches the REINTRODUCTION of an exact retired
// identifier. It cannot catch every descendant of a retired word — a method named for the verb form of a
// retired type (`Appraise`, from `ISalienceAppraiser`) is not that type's name, so no rule here would have
// flagged it. That kind of drift needs a reader.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(import.meta.url);
const repo = path.resolve(path.dirname(here), '..', '..');

/** The committed API baselines — one flat text file per packable assembly, regenerated by the test suite. */
export const BASELINE_DIR = 'tests/Lyntai.Tests/Api/Baselines';

/**
 * Every C# identifier on one baseline line.
 *
 * Splitting on non-identifier characters is what makes `IEnumerable<IMemoryAgePolicy> agePolicies` four
 * tokens and `Lyntai.Memory.Modulation.ModulatedRetrievability` four more — so a rule can name exactly the
 * identifier it retired without also naming everything that merely contains it.
 */
export const identifiers = (line) => line.match(/[A-Za-z_][A-Za-z0-9_]*/g) ?? [];

const describeRule = (rule, index) =>
  (Array.isArray(rule.names) && rule.names.length ? rule.names.join(', ')
    : rule.pattern ? `/${rule.pattern}/`
      : `retiredApiNames[${index}]`);

/**
 * Compile the registry, scan the baselines, and report registry defects alongside the hits.
 *
 * A malformed rule is a PROBLEM rather than a silent skip: a rule that can never match is indistinguishable
 * from a clean tree, which is the whole class of failure this gate exists to end.
 */
export function scanApiVocabulary(repoRoot, config, { baselineDir = BASELINE_DIR } = {}) {
  const rules = config.retiredApiNames ?? [];
  const problems = [];
  const hits = [];

  const dir = path.join(repoRoot, baselineDir);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort() : [];

  if (rules.length === 0) return { files, lines: 0, hits, problems, empty: true };

  const compiled = [];
  for (const [index, rule] of rules.entries()) {
    const label = describeRule(rule, index);
    const hasNames = Array.isArray(rule.names) && rule.names.length > 0;
    const hasPattern = typeof rule.pattern === 'string' && rule.pattern.length > 0;
    if (hasNames === hasPattern) {
      problems.push({
        what: `retiredApiNames[${index}] (${label}) declares ${hasNames ? 'BOTH `names` and `pattern`' : 'neither `names` nor `pattern`'}`,
        fix: 'give it exactly one: `names` for exact identifiers, `pattern` for an identifier SHAPE',
      });
      continue;
    }
    if (!rule.use || !rule.why) {
      problems.push({
        what: `retiredApiNames[${index}] (${label}) has no \`${rule.use ? 'why' : 'use'}\``,
        fix: 'every entry says what to use instead and why — a rule that only refuses teaches nothing',
      });
      continue;
    }

    let test;
    if (hasNames) {
      const set = new Set(rule.names);
      test = (token) => set.has(token);
    } else {
      let re;
      // Anchored to the WHOLE token, so a pattern is an identifier SHAPE (`\w*Dto\w*`) and can never
      // become an accidental substring rule.
      try { re = new RegExp(`^(?:${rule.pattern})$`); } catch (e) {
        problems.push({ what: `retiredApiNames[${index}] (${label}) is not a valid regex: ${e.message}`, fix: 'fix the pattern' });
        continue;
      }
      test = (token) => re.test(token);
    }

    const allow = [];
    for (const [j, a] of (rule.allow ?? []).entries()) {
      if (!a?.signature || !a?.why) {
        problems.push({
          what: `retiredApiNames[${index}] (${label}) allowance #${j} has no \`${a?.signature ? 'why' : 'signature'}\``,
          fix: 'an escape states the EXACT signature it permits and why it is right — an escape without a '
            + 'reason is a silent exclusion, which is what this gate exists to prevent',
        });
        continue;
      }
      allow.push({ signature: a.signature.trim(), why: a.why, used: 0 });
    }
    compiled.push({ rule, label, test, allow });
  }

  let lines = 0;
  for (const file of files) {
    const text = fs.readFileSync(path.join(dir, file), 'utf8');
    const fileLines = text.split(/\r?\n/);
    lines += fileLines.length;
    fileLines.forEach((line, i) => {
      if (!line.trim()) return;
      const tokens = identifiers(line);
      if (!tokens.length) return;
      for (const entry of compiled) {
        const matched = [...new Set(tokens.filter(entry.test))];
        if (!matched.length) continue;
        // The escape is keyed on the EXACT signature, so it expires the moment that signature changes —
        // an allowance cannot outlive the thing it justified without this gate saying so.
        const allowance = entry.allow.find((a) => a.signature === line.trim());
        if (allowance) { allowance.used++; continue; }
        hits.push({ file, line: i + 1, rule: entry.rule, label: entry.label, tokens: matched, text: line.trim() });
      }
    });
  }

  for (const entry of compiled)
    for (const a of entry.allow)
      if (a.used === 0)
        problems.push({
          what: `retiredApiNames (${entry.label}) allows a signature that no baseline contains:\n      ${a.signature}`,
          fix: 'delete the allowance — the surface it justified is gone, so the escape now only hides the '
            + 'NEXT occurrence of the same mistake',
        });

  return { files, lines, hits, problems, empty: false };
}

/** The gate, reporting through the given sinks. Returns the process exit code. */
export function checkApiVocabulary(repoRoot = repo, config, log = console.log, err = console.error,
  options = {}) {
  const { files, lines, hits, problems, empty } = scanApiVocabulary(repoRoot, config, options);

  // Fail-closed: a gate that scanned nothing must never print a tick. The baselines are generated by the
  // test suite, so an empty directory means either a fresh clone that has not run it or a wrong path here —
  // both of which make every check below vacuous.
  if (files.length === 0) {
    err(`check-api-vocabulary: ✗ found no API baselines under ${options.baselineDir ?? BASELINE_DIR}`);
    err('  Nothing was scanned, so this gate proves nothing. Run `node devtools/dev.mjs test` to seed them.');
    return 1;
  }

  if (empty) {
    log('check-api-vocabulary: no retired API names configured — nothing to check.');
    return 0;
  }

  if (!hits.length && !problems.length) {
    log(`check-api-vocabulary: ${files.length} baseline(s), ${lines} line(s) of public surface clean of `
      + 'retired names ✓');
    return 0;
  }

  if (hits.length) {
    err(`\ncheck-api-vocabulary: ✗ ${hits.length} retired name(s) in the FROZEN public surface`);
    err('  Named arguments and type names are source-compatible surface — after a freeze each of these');
    err('  costs a major version.\n');
    const byRule = new Map();
    for (const hit of hits) {
      if (!byRule.has(hit.rule)) byRule.set(hit.rule, []);
      byRule.get(hit.rule).push(hit);
    }
    for (const [rule, group] of byRule) {
      err(`  ${group[0].label} — use ${rule.use} instead`);
      err(`    why: ${rule.why}`);
      for (const hit of group) {
        const excerpt = hit.text.length > 108 ? hit.text.slice(0, 105) + '...' : hit.text;
        err(`    ${hit.file}:${hit.line}  [${hit.tokens.join(' ')}]  ${excerpt}`);
      }
      err('');
    }
    err('  A baseline is GENERATED, so `drift-ok` cannot live in it — the next regeneration would erase it.');
    err('  If one of these names is DELIBERATE, add an allowance to that rule\'s `allow` in');
    err('  devtools/project.config.mjs: the exact signature line, and why it is right.');
  }

  if (problems.length) {
    err(`\ncheck-api-vocabulary: ✗ ${problems.length} problem(s) in the retiredApiNames registry`);
    for (const { what, fix } of problems) err(`  • ${what}\n      → ${fix}`);
  }
  return 1;
}

// CLI entry point — a thin wrapper, so importing this module for a test reads no baseline.
// `import.meta.main` where the runtime has it (Node >= 24.2); the argv fallback compares resolved paths,
// and a wrong comparison makes this gate silently do NOTHING and exit 0. Pinned by cli-entry.test.mjs.
if (import.meta.main ?? (process.argv[1] && path.resolve(process.argv[1]) === here)) {
  const config = (await import('../project.config.mjs')).default;
  process.exitCode = checkApiVocabulary(repo, config);
}
